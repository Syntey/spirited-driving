import FirebaseCore
import FirebaseCrashlytics
import Foundation
import KMP

// Crashlytics calls are skipped when Firebase isn't configured, see `AppDelegate`.
final class PlatformFirebaseCrashlyticsImpl: PlatformFirebaseCrashlytics {

    // Kotlin may call these from any thread. Crashlytics itself is thread-safe.
    nonisolated func logMessage(message: String) {
        guard FirebaseApp.app() != nil else {
            return
        }
        Crashlytics.crashlytics().log(message)
    }

    nonisolated func sendNonFatalException(nsException: NSException) {
        guard FirebaseApp.app() != nil else {
            return
        }
        Crashlytics.crashlytics().record(exceptionModel: nsException.asNonFatalExceptionModel())
    }

    nonisolated func raiseFatalException(nsException: NSException) {
        // In case of fatal exception, we just raise it and native Crashlytics SDK will do the rest,
        // as provided `nsException` is already configured by Kotlin to provide
        // meaningful output in Crashlytics console
        nsException.raise()
    }
}

extension NSException {

    /**
     Converts the `NSException` generated by Kotlin to `ExceptionModel` used by Firebase Crashlytics to log non-fatals.
     */
    nonisolated func asNonFatalExceptionModel() -> ExceptionModel {
        let exceptionModel = ExceptionModel(
            name: self.name.rawValue,
            reason: self.reason ?? ""
        )

        exceptionModel.stackTrace = self.callStackReturnAddresses.map { address in
            StackFrame(address: address.uintValue)
        }

        return exceptionModel
    }
}
