// Generates the app icon for iOS (an Icon Composer document) and Android (adaptive icon drawables) from one geometry:
// a road, its dashed centre line and a car. Change the numbers here and rerun; the outputs are overwritten.
//
// Usage: node tools/app-icon/generate.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '../..');
const r1 = (v) => String(Math.round(v * 10) / 10);
const NOTE = 'Generated by tools/app-icon/generate.mjs: change the icon there, not here';

// ---------- colours ----------
const RED = '#BD162C';
const ASPHALT = '#2C323A';
const WHITE = '#FFFFFF';
const GRAPHITE = '#16191D';
const RED_DARK = '#FC4952';
const LINE_DARK = '#8A949F';

// ---------- road ----------
// Both ends lie outside the 1024 square on purpose.
const P = [
  [170, 1330],
  [170, 560],
  [854, 464],
  [854, -306],
];
const ROAD_WIDTH = 300;
const LINE_WIDTH = 18;
const DASH = 56;
const GAP = 52;
const SAMPLES = 4000;
// The Android layer is 1536 units with the 1024 square centred in it.
const ANDROID_OFFSET = 256;

// ---------- car (same proportions as CarShape in CarSpinner.kt) ----------
const CAR_LENGTH = 360;
const CAR_WIDTH = (CAR_LENGTH * 0.46) / 0.9;
const CORNER = 0.35 * CAR_WIDTH;

const pt = ([x, y], off = 0) => `${r1(x + off)} ${r1(y + off)}`;

function bez(t) {
  const u = 1 - t;
  const a = u * u * u;
  const b = 3 * u * u * t;
  const c = 3 * u * t * t;
  const d = t * t * t;
  return [0, 1].map((k) => a * P[0][k] + b * P[1][k] + c * P[2][k] + d * P[3][k]);
}

function bezDerivative(t) {
  const u = 1 - t;
  return [0, 1].map(
    (k) =>
      3 * (u * u * (P[1][k] - P[0][k]) + 2 * u * t * (P[2][k] - P[1][k]) + t * t * (P[3][k] - P[2][k])),
  );
}

function roadD(off) {
  return `M${pt(P[0], off)}C${pt(P[1], off)} ${pt(P[2], off)} ${pt(P[3], off)}`;
}

// Arc length table, so dashes are measured along the curve, not by t.
const arc = [0];
let total = 0;
let prev = bez(0);
for (let i = 1; i <= SAMPLES; i++) {
  const q = bez(i / SAMPLES);
  total += Math.hypot(q[0] - prev[0], q[1] - prev[1]);
  arc.push(total);
  prev = q;
}

function pointAtArc(s) {
  if (s >= total) return bez(1);
  let lo = 0;
  let hi = SAMPLES;
  while (hi - lo > 1) {
    const mid = (lo + hi) >> 1;
    if (arc[mid] <= s) lo = mid;
    else hi = mid;
  }
  const f = (s - arc[lo]) / (arc[lo + 1] - arc[lo]);
  return bez((lo + f) / SAMPLES);
}

function centreD(off) {
  const dashes = [];
  for (let s = 0; s < total; s += DASH + GAP) {
    const a = pointAtArc(s);
    const b = pointAtArc(Math.min(s + DASH, total));
    dashes.push(`M${pt(a, off)} L${pt(b, off)}`);
  }
  return dashes.join(' ');
}

// ---------- car ----------
const L = CAR_LENGTH;
const W = CAR_WIDTH;
const C = CORNER;
const top = -L / 2;
const bottom = L / 2;
const left = -W / 2;
const right = W / 2;

const centre = bez(0.5);
const tangent = bezDerivative(0.5);
const theta = Math.atan2(tangent[0], -tangent[1]);
const cosT = Math.cos(theta);
const sinT = Math.sin(theta);

function carD(off) {
  const p = (x, y) => {
    const X = centre[0] + x * cosT - y * sinT;
    const Y = centre[1] + x * sinT + y * cosT;
    return pt([X, Y], off);
  };
  const arcTo = (x, y) => `A${r1(C)} ${r1(C)} 0 0 1 ${p(x, y)}`;
  const body = [
    `M${p(left + C, top)}`,
    `L${p(right - C, top)}`,
    arcTo(right, top + C),
    `L${p(right, bottom - C)}`,
    arcTo(right - C, bottom),
    `L${p(left + C, bottom)}`,
    arcTo(left, bottom - C),
    `L${p(left, top + C)}`,
    arcTo(left + C, top),
    'Z',
  ].join(' ');
  // Trapezoid window from y0 (inset i0) to y1 (inset i1), insets as fractions of W.
  const window = (y0, i0, y1, i1) =>
    `M${p(left + i0 * W, y0)} L${p(right - i0 * W, y0)} L${p(right - i1 * W, y1)} L${p(left + i1 * W, y1)} Z`;
  const windscreen = window(top + 0.22 * L, 0.2, top + 0.38 * L, 0.12);
  const rearWindow = window(top + 0.7 * L, 0.12, top + 0.8 * L, 0.2);
  return `${body} ${windscreen} ${rearWindow}`;
}

// Road outline for the Android monochrome layer: both edges, 48 samples each.
function roadOutlineD(off) {
  const N = 48;
  const half = ROAD_WIDTH / 2;
  const plus = [];
  const minus = [];
  for (let i = 0; i < N; i++) {
    const t = i / (N - 1);
    const q = bez(t);
    const d = bezDerivative(t);
    const len = Math.hypot(d[0], d[1]);
    const nx = -d[1] / len;
    const ny = d[0] / len;
    plus.push([q[0] + nx * half, q[1] + ny * half]);
    minus.push([q[0] - nx * half, q[1] - ny * half]);
  }
  const ring = [...plus, ...minus.reverse()];
  return `M${ring.map((p) => pt(p, off)).join(' L')} Z`;
}

// ---------- iOS ----------
const srgb = (hex) => {
  const channels = [1, 3, 5].map((i) => (parseInt(hex.slice(i, i + 2), 16) / 255).toFixed(5));
  return `srgb:${channels.join(',')},1.00000`;
};

const svg = (body) =>
  [
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024">',
    `  <!-- ${NOTE} -->`,
    `  ${body}`,
    '</svg>',
    '',
  ].join('\n');

const iconDir = path.join(ROOT, 'iosApp/SpiritedDriving/Resources/AppIcon.icon');
const assetsDir = path.join(iconDir, 'Assets');

const layerShadow = { kind: 'neutral', opacity: 0.5 };
const layerTranslucency = { enabled: false, value: 0.5 };

const iconJson = {
  fill: { solid: srgb(RED) },
  'fill-specializations': [
    { value: { solid: srgb(RED) } },
    { appearance: 'dark', value: { solid: srgb(GRAPHITE) } },
  ],
  groups: [
    {
      layers: [
        {
          glass: true,
          'image-name': 'car.svg',
          name: 'car',
          'fill-specializations': [{ appearance: 'dark', value: { solid: srgb(RED_DARK) } }],
        },
      ],
      shadow: layerShadow,
      translucency: layerTranslucency,
    },
    {
      layers: [
        {
          glass: true,
          'image-name': 'centre-line.svg',
          name: 'centre-line',
          'fill-specializations': [{ appearance: 'dark', value: { solid: srgb(LINE_DARK) } }],
        },
      ],
      shadow: layerShadow,
      translucency: layerTranslucency,
    },
    {
      layers: [{ glass: true, 'image-name': 'road.svg', name: 'road' }],
      shadow: layerShadow,
      translucency: layerTranslucency,
    },
  ],
  'supported-platforms': { circles: ['watchOS'], squares: 'shared' },
};

// ---------- Android ----------
const XML_HEAD = `<?xml version="1.0" encoding="utf-8"?>\n<!-- ${NOTE} -->\n`;
const VECTOR_OPEN = [
  '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
  '    android:width="108dp"',
  '    android:height="108dp"',
  '    android:viewportWidth="1536"',
  '    android:viewportHeight="1536">',
];

const foregroundXml =
  XML_HEAD +
  [
    ...VECTOR_OPEN,
    '    <path',
    `        android:pathData="${roadD(ANDROID_OFFSET)}"`,
    `        android:strokeColor="${ASPHALT}"`,
    `        android:strokeWidth="${ROAD_WIDTH}" />`,
    '    <path',
    `        android:pathData="${centreD(ANDROID_OFFSET)}"`,
    `        android:strokeColor="${WHITE}"`,
    `        android:strokeWidth="${LINE_WIDTH}" />`,
    '    <path',
    `        android:pathData="${carD(ANDROID_OFFSET)}"`,
    `        android:fillColor="${WHITE}"`,
    '        android:fillType="evenOdd" />',
    '</vector>',
    '',
  ].join('\n');

const monochromeXml =
  XML_HEAD +
  [
    ...VECTOR_OPEN,
    '    <path',
    `        android:pathData="${roadOutlineD(ANDROID_OFFSET)} ${carD(ANDROID_OFFSET)}"`,
    `        android:fillColor="${WHITE}"`,
    '        android:fillType="evenOdd" />',
    '</vector>',
    '',
  ].join('\n');

const resDir = path.join(ROOT, 'androidApp/src/main/res');

const backgroundXml =
  XML_HEAD +
  ['<resources>', `    <color name="ic_launcher_background">${RED}</color>`, '</resources>', ''].join('\n');

const adaptiveXml =
  XML_HEAD +
  [
    '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">',
    '    <background android:drawable="@color/ic_launcher_background" />',
    '    <foreground android:drawable="@drawable/ic_launcher_foreground" />',
    '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />',
    '</adaptive-icon>',
    '',
  ].join('\n');

// ---------- write ----------
function write(file, text) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, text);
}

write(path.join(assetsDir, 'road.svg'), svg(`<path d="${roadD(0)}" fill="none" stroke="${ASPHALT}" stroke-width="${ROAD_WIDTH}"/>`));
write(
  path.join(assetsDir, 'centre-line.svg'),
  svg(`<path d="${centreD(0)}" fill="none" stroke="${WHITE}" stroke-width="${LINE_WIDTH}"/>`),
);
write(path.join(assetsDir, 'car.svg'), svg(`<path fill="${WHITE}" fill-rule="evenodd" d="${carD(0)}"/>`));
write(path.join(iconDir, 'icon.json'), `${JSON.stringify(iconJson, null, 2)}\n`);

write(path.join(resDir, 'drawable/ic_launcher_foreground.xml'), foregroundXml);
write(path.join(resDir, 'drawable/ic_launcher_monochrome.xml'), monochromeXml);
write(path.join(resDir, 'values/ic_launcher_background.xml'), backgroundXml);
write(path.join(resDir, 'mipmap-anydpi/ic_launcher.xml'), adaptiveXml);

console.log(`Wrote app icon to ${path.relative(ROOT, iconDir)} and ${path.relative(ROOT, resDir)}`);
